#!/usr/bin/env python3
"""Reproducible, lossless TGPaintModel -> Compose Path port. No runtime Java dependency."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'common/TuxGuitar-lib/src/main/java/app/tuxguitar/graphics/control/painters'
OUTPUT = ROOT / 'compose/tux-compose-core/src/commonMain/kotlin/com/tuxcompose/renderer/glyphs'
SOURCES = ['TGClefPainter', 'TGNotePainter', 'TGKeySignaturePainter', 'TGSilencePainter', 'TGNumberPainter']

def balanced(text, start):
    level = 1
    for i in range(start, len(text)):
        if text[i] == '(':
            level += 1
        elif text[i] == ')':
            level -= 1
            if level == 0:
                return text[start:i], i + 1
    raise ValueError('Unbalanced Java model')

def extract(text):
    result = []
    cursor = 0
    while (match := re.search(r'new TGPaintModel\(', text[cursor:])):
        start = cursor + match.end()
        body, end = balanced(text, start)
        prefix = text[cursor:cursor + match.start()]
        names = re.findall(r'(\w+)_MODEL\s*=', prefix)
        name = names[-1] if names else f'DIGIT_{len(result)}'
        result.append((name, body))
        cursor = end
    return result

def arguments(body):
    # Split on commas outside parentheses (TGRectangle contains arithmetic groups).
    level, start = 0, 0
    for i, char in enumerate(body):
        if char == '(':
            level += 1
        elif char == ')':
            level -= 1
        elif char == ',' and level == 0:
            yield body[start:i].strip()
            start = i + 1
    yield body[start:].strip()

def numeric(value):
    expression = re.sub(r'(?<=[0-9])f\b', '', value)
    if not re.fullmatch(r'[0-9eE.()+*/\s-]+', expression):
        raise ValueError(value)
    return float(eval(expression, {'__builtins__': {}}, {}))

def generate():
    files = {}
    manifest = {}
    for source in SOURCES:
        text = (SOURCE / f'{source}.java').read_text()
        lines = [
            '// SPDX-License-Identifier: LGPL-2.1-or-later',
            '// Generated by tools/port_glyphs.py. Do not edit. Coordinates are unchanged from TuxGuitar.',
            '// Copyright (C) 2005-2022 Julian Casadesus; 2023-2025 TuxGuitar contributors.',
            'package com.tuxcompose.renderer.glyphs', '',
            'import androidx.compose.ui.geometry.Rect',
            'import androidx.compose.ui.graphics.Path', '',
            f'internal object {source} {{',
        ]
        names = []
        for name, body in extract(text):
            names.append(name)
            lines.append(f'    val {name}: TGVectorGlyph by lazy {{')
            lines.append('        TGVectorGlyph(Path().apply {')
            cursor = 0
            xs, ys = [], []
            while (match := re.search(r'new TG(MoveTo|LineTo|CubicTo|Rectangle)\(', body[cursor:])):
                start = cursor + match.end()
                args_body, end = balanced(body, start)
                args = list(arguments(args_body))
                kind = match[1]
                call = {'MoveTo': 'moveTo', 'LineTo': 'lineTo', 'CubicTo': 'cubicTo', 'Rectangle': 'addRect'}[kind]
                values = [numeric(a) for a in args]
                if kind == 'Rectangle':
                    x,y,w,h = args
                    xs.extend([values[0],values[0]+values[2]])
                    ys.extend([values[1],values[1]+values[3]])
                    lines.append(f'            addRect(Rect({x}, {y}, {x} + {w}, {y} + {h}))')
                else:
                    xs.extend(values[::2]); ys.extend(values[1::2])
                    lines.append(f'            {call}({", ".join(args)})')
                cursor = end
            if not xs:
                raise ValueError(f'Empty {source}/{name}')
            def f(v):
                s = str(v)
                return s + 'f'
            # Upstream command bounds include Bezier controls (not just exact curve extrema).
            lines.append(f'        }}, {f(max(xs) - min(xs))}, {f(max(ys) - min(ys))})')
            lines.append('    }')
        if source == 'TGNumberPainter':
            lines.append(f'    fun digit(value: Int): TGVectorGlyph = when (value) {{')
            lines.extend(f'        {i} -> {name}' for i,name in enumerate(names))
            lines.append('        else -> error("Not a digit: $value")')
            lines.append('    }')
        lines.append('}')
        files[OUTPUT / f'{source}.kt'] = '\n'.join(lines) + '\n'
        manifest[source] = {'sha256': hashlib.sha256(text.encode()).hexdigest(), 'models': names}
    files[ROOT / 'compose/docs/glyph-provenance.json'] = json.dumps(manifest, indent=2) + '\n'
    return files

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('Verified all 32 upstream vector models.' if args.check else 'Ported upstream vector models.')

if __name__ == '__main__':
    main()
