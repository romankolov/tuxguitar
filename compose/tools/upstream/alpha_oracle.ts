import {Skyline} from '@coderline/alphatab/rendering/skyline/Skyline';
import {SkylineScratch} from '@coderline/alphatab/rendering/skyline/SkylineScratch';
import {BarLayoutingInfo} from '@coderline/alphatab/rendering/staves/BarLayoutingInfo';
import {AccidentalGroupGlyph} from '@coderline/alphatab/rendering/glyphs/AccidentalGroupGlyph';

const lines=['# alphaTab 1.9.0 9f1aa10460df1b326123d28a2222f7b20d081e61; generated by actual upstream classes'];
let seed=0x10ab29;
function random(max:number) {seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed%max;}
for(let run=0;run<8;run++) {
    const skyline=new Skyline(0,256,new SkylineScratch());
    lines.push('reset\t0\t256');
    for(let i=0;i<256;i++) {
        const a=random(256),b=Math.min(256,a+1+random(32)),height=random(100);
        skyline.insert(a,b,height,0);
        const q=random(256),r=Math.min(256,q+1+random(64));
        lines.push(['sky',a,b,height,q,r,skyline.placeAbove(q,r,0,0),skyline.segmentCount].join('\t'));
    }
}
for(const ratio of [1.2,Math.SQRT2,1.5,1.618,2]) {
    for(let run=0;run<16;run++) {
        const info=new BarLayoutingInfo(ratio,0,0,60);
        let tick=0;
        const rods:number[]=[];
        for(let i=0;i<2+run%6;i++) {
            const duration=[60,120,240,480,960][random(5)];
            const rod=random(32);
            rods.push(rod);
            info.addSpring(tick,duration,0,0,rod);
            tick+=duration;
        }
        info.finish();
        const springs=Array.from(info.springs.values()).sort((a,b)=>a.timePosition-b.timePosition);
        const minima=springs.map(s=>s.minWidth);
        const weights=springs.map(s=>1/s.springConstant);
        const minimum=minima.reduce((a,b)=>a+b,0);
        for(const slack of [0,1,17,80,300]) {
            const target=minimum+slack;
            const force=info.spaceToForce(target);
            const pos=info.buildOnTimePositions(force).slice();
            const end=info.calculateVoiceWidth(force);
            const widths=pos.map((x,i)=>(pos[i+1]??end)-x);
            lines.push(['spring',minima.join(','),weights.join(','),target,widths.join(',')].join('\t'));
        }
    }
}
for(let run=0;run<128;run++) {
    const group=new AccidentalGroupGlyph();
    const inputs=Array.from({length:2+run%13},(_,id)=>({id,y:random(64)-32,height:5+random(24),width:8,x:0,doLayout(){}}));
    const original=inputs.map(g=>[g.y,g.height]);
    (group as any).glyphs=inputs;
    (group as any).renderer={smuflMetrics:{accidentalPadding:1,oneStaffSpace:8}};
    group.doLayout();
    const cols=inputs.slice().sort((a,b)=>a.id-b.id).map(g=>Math.round((group.width-g.x)/9-1));
    lines.push(['columns',original.map(v=>v.join(',')).join(';'),cols.join(',')].join('\t'));
}
console.log(lines.join('\n'));
